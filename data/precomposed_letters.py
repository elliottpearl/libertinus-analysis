# Generated from the patched fonts by measuring, per style:
#   - the side: a letter inherits above only if none of its marks is above (ccc 230), and
#     below only if none is below or attached below (ccc 220, 202: cedilla, ogonek);
#   - the source: the deepest Unicode base, except that i and j inherit below from
#     dotless ı and ȷ, which their precomposed glyphs are built on; i and j with a below
#     mark (ḭ ị) keep their dot, as BASE_ABOVE already left them out;
#   - the match, on the inherited side only (above: y 150 up; below: y 250 down), so a fused
#     cedilla, ogonek or horn on the other side does not count: the base letter's ink intervals
#     are paired with the precomposed glyph's (as stem_shift in stage 8) and fitted with a shift
#     and a scale of up to 15%; at least 80% must fit. Control points are no use here: where the
#     designer redrew the letter (italic Ą, semibold ą), only 5-17% of them survive, though the
#     shape does (italic ą: crossings within 4 units);
#   - the shift of the anchor that follows from the fit. Stage 9 must add it: semibold italic
#     builds most precomposed glyphs with the base 12 right, the italic capitals with an accent
#     above are drawn about 5% wider (Ǡ Ǣ Ǧ Ǩ Ą: scale 1.03-1.06), and a few glyphs are offset
#     (italic Ĵ -50, ṏ -40). 35 glyphs need the scale in some style;
#   - collisions: no IPA mark on that side may overlap the precomposed glyph more than it
#     overlaps the base letter at the same anchor.
# Stage 9 never replaces an anchor the glyph already has (designer or curated).
#
# Compared with BASE_ABOVE: 32 added, 0 dropped.
