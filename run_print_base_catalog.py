#!/usr/bin/env python3
"""
The base catalog: each base group of data/ipa/ipa_unicode.py as a list of
characters without marks, in the four styles, for the report's "Bases"
section. Writes tex/input/bases_{name}.tex, which tex/libertinus-analysis.tex
\\inputs. Run from the repo root, after run_patch_font.py (the lists are set
in the patched fonts, which have the drafts of stage 2).

Small capitals are set in the original fonts: the patched fonts' GSUB has
only ccmp (stage 10 rebuilds GSUB from ccmp.fea), so \\textsc does nothing
in them.
"""

from fontTools.ttLib import TTFont

from libertinus_analysis.config import TEX_INPUT_DIR
from libertinus_analysis.font_context import FONTS
from data.ipa import ipa_unicode as U

# (output name, unicode_groups key or a list of codepoints, small caps)
CATALOG = [
    ("latin", "BASE_LATIN", False),
    ("ipa", "BASE_IPA", False),
    ("superscript", "BASE_SUPERSCRIPT_CONSONANT", False),
    ("small_capital", "BASE_SMALL_CAPITAL", True),
    ("precomposed_above", "PRECOMPOSED_ABOVE", False),
    ("precomposed_below", "PRECOMPOSED_BELOW", False),
    ("precomposed_stacked", "BASE_PRECOMPOSED_ANCHOR_RELEVANT", False),
    ("no_mark", "BASE_NO_MARK", False),
    ("greek", "BASE_GREEK", False),
    ("cyrillic", "BASE_CYRILLIC", False),
]

STYLES = ["regular_patch", "italic_patch", "semibold_patch", "semibold_italic_patch"]


def dedupe(cps):
    seen = set()
    return [cp for cp in cps if not (cp in seen or seen.add(cp))]


def small_capital_precomposed():
    """
    The codepoints whose small capital is a precomposed glyph of
    base_small_capital_glyph: each glyph name is resolved to the codepoint
    that the original regular font's smcp maps to it. Base letters (a.sc, ae.sc,
    ...) are left out: they are BASE_SMALL_CAPITAL. Prints the names that no
    codepoint reaches.
    """
    font = TTFont(FONTS["regular"]["path"])
    cmap = font.getBestCmap()
    gsub = font["GSUB"].table
    to_sc = {}
    for fr in gsub.FeatureList.FeatureRecord:
        if fr.FeatureTag != "smcp":
            continue
        for li in fr.Feature.LookupListIndex:
            lookup = gsub.LookupList.Lookup[li]
            for st in lookup.SubTable:
                if lookup.LookupType == 7:
                    st = st.ExtSubTable
                for src, dst in getattr(st, "mapping", {}).items():
                    # one glyph for one (Libertinus's smcp is mostly a
                    # multiple substitution to one glyph); not ā -> a.sc macron
                    if isinstance(dst, list):
                        dst = dst[0] if len(dst) == 1 else None
                    if dst is not None:
                        to_sc.setdefault(dst, set()).add(src)
    name_to_cp = {}
    for cp, name in sorted(cmap.items()):
        name_to_cp.setdefault(name, cp)
    bases = set(U.base_small_capital)
    out = []
    for sc in dedupe(U.base_small_capital_glyph):
        src = sc[:-len(".sc")] if sc.endswith(".sc") else None
        cp = name_to_cp.get(src) if src in to_sc.get(sc, ()) else None
        if cp is None:
            print(f"  small capital {sc}: no codepoint maps to it in smcp, left out")
        elif cp not in bases:
            out.append(cp)
    return out


STYLE_SWITCH = ["", "\\itshape ", "\\bfseries ", "\\itshape\\bfseries "]


def cmap_of(style):
    return TTFont(FONTS[style]["path"]).getBestCmap()


def lines(cps, styles, small_caps=False):
    """
    One paragraph per style, as \\ribbi sets them, each without the letters
    that style's font lacks (which would otherwise show as boxes). Prints them.
    """
    family = "" if small_caps else "\\LibertinusSerifPatch"
    out = []
    for style, switch in zip(styles, STYLE_SWITCH):
        cmap = cmap_of(style)
        gone = [cp for cp in cps if cp not in cmap]
        if gone:
            print(f"  {style}: missing {' '.join(chr(c) for c in gone)}")
        chars = " ".join(f'\\char"{cp:04X}\\gs' for cp in cps if cp in cmap)
        if small_caps:
            chars = f"\\textsc{{{chars}}}"
        out.append(f"{{{family}{switch}\n\t{chars}\n}}\n")
    return "\n".join(out)


def main():
    for name, group, small_caps in CATALOG:
        cps = dedupe(U.unicode_groups[group]["items"])
        print(f"{group}, {len(cps)} characters")
        styles = [s.removesuffix("_patch") for s in STYLES] if small_caps else STYLES
        body = lines(cps, styles, small_caps)
        if name == "small_capital":
            body += "\n\\medskip\n\n" + lines(small_capital_precomposed(), styles, small_caps=True)
        path = TEX_INPUT_DIR / f"bases_{name}.tex"
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"% generated by run_print_base_catalog.py: {group} ({len(cps)} characters)\n")
            f.write(body)


if __name__ == "__main__":
    main()
