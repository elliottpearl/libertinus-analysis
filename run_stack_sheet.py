"""
Stacked above marks: draft fonts and test sheet (see stack_drafts.py).

    .venv/bin/python run_stack_sheet.py
    cd tex && xelatex stack_test_sheet.tex
"""
import sys

import uharfbuzz as hb

sys.path.insert(0, "src")
sys.path.insert(0, ".")
from libertinus_analysis.stack_drafts import (FILE, MARKS, PROPORTIONAL_K, UNIFORM_K,  # noqa: E402
                                              VARIANTS, draft_stacks)

CGJ = "͏"
LABEL = {"regular": "Regular", "italic": "Italic", "semibold": "Semibold", "semibold_italic": "Semibold italic"}
SHAPE = {"regular": r"\upshape\mdseries", "italic": r"\itshape\mdseries",
         "semibold": r"\upshape\bfseries", "semibold_italic": r"\itshape\bfseries"}
VLABEL = {"orig": "original", "patch": "patched", "U": f"draft U (uniform, {UNIFORM_K} × median)",
          "P": f"draft P (proportional, {PROPORTIONAL_K} × own gap)"}
# letter + first mark composes into a precomposed letter, the second mark attaches to it
PRECOMPOSED_PATH = ["ä̀", "à̈", "ö̀", "ò̈", "ü̆", "ŭ̈", "ë́", "é̈",
                    "ā́", "á̄", "ã̀", "à̃", "ẽ́", "é̃", "ǎ́", "á̌",
                    "ǡ", "â̈", "å̀", "ŏ̃",
                    "Ä̀", "À̈", "Ö́", "Ā́", "Ã̀", "Ë̄", "Ü̆", "Å̀"]
# letters with no precomposed form: mark-to-mark
NO_PRECOMPOSED = ["ɛ̃́", "ɔ̃́", "ə̃̀", "ɛ̃̀", "ɔ̃̂",
                  "ɪ̃́", "ʊ̃̀", "ŋ̈̀", "ə̈́", "ɨ̄́",
                  "ʌ̃̄", "ɑ̃̌", "ŋ́̄", "ɲ̊́"]
# the whole triplet has a precomposed form: typed plainly, normalization takes the designer's glyph
TRIPLETS = ["ǜ", "ǘ", "ǚ", "ǟ", "ṍ",
            "ṏ", "ḗ", "ṑ", "ǻ", "ắ",
            "ẫ", "ǡ", "Ǘ", "Ṍ"]
NAME = {0x0300: "grave", 0x0301: "acute", 0x0302: "circumflex", 0x0303: "tilde", 0x0304: "macron",
        0x0306: "breve", 0x0307: "dot", 0x0308: "diaeresis", 0x030A: "ring", 0x030C: "caron"}
FIRST = MARKS
SECOND = MARKS


def tex(s):
    return "".join(r"\ " if c == " " else f'\\char"{ord(c):04X}' for c in s)


def glyph_count(path, s):
    f = hb.Font(hb.Face(hb.Blob.from_file_path(path)))
    b = hb.Buffer()
    b.add_str(s)
    b.guess_segment_properties()
    hb.shape(f, b, {})
    return len(b.glyph_infos)


def main():
    fonts = {}
    for st in FILE:
        fonts[(st, "orig")] = f"LibertinusSerif-{FILE[st]}.otf"
        fonts[(st, "patch")] = f"LibertinusSerif-{FILE[st]}-patch.otf"
        for v in VARIANTS:
            fonts[(st, v)] = f"LibertinusSerif-{FILE[st]}-stack{v}.otf"
    info = {}
    for st in FILE:
        for v in VARIANTS:
            _, info[(st, v)] = draft_stacks(st, v, "fonts/" + fonts[(st, v)])
        print(f"{st}: {len(info[(st, 'U')]['bases'])} precomposed letters with a stack anchor")
    # keep the precomposed-path strings that do shape as [precomposed letter, mark]
    pre = [s for s in PRECOMPOSED_PATH if glyph_count("fonts/" + fonts[("regular", "patch")], s) == 2]
    dropped = [s for s in PRECOMPOSED_PATH if s not in pre]
    if dropped:
        print("not [letter, mark] in regular, left out:", dropped)

    L = [r"""% Generated by run_stack_sheet.py; do not edit.
\documentclass[10pt]{article}
\usepackage{fontspec}
\usepackage{xcolor}
\usepackage{array}
\usepackage{geometry}
\geometry{a4paper, landscape, left=1.1cm, right=1.1cm, top=1.1cm, bottom=1.1cm}
\setlength{\parindent}{0pt}
\definecolor{draft}{RGB}{20,70,190}
\setmainfont{Libertinus Serif}[Path = ../fonts/, UprightFont = LibertinusSerif-Regular.otf, ItalicFont = LibertinusSerif-Italic.otf, BoldFont = LibertinusSerif-Semibold.otf, BoldItalicFont = LibertinusSerif-SemiboldItalic.otf]"""]
    macro = {}
    letters = "abcdefghijklmnopqrstuvwxyz"
    for k, (key, file) in enumerate(fonts.items()):
        macro[key] = r"\Fnt" + letters[k // 26] + letters[k % 26]
        L.append(rf"\newfontfamily{macro[key]}[Path = ../fonts/]{{{file}}}")
    L.append(r"""\begin{document}
\section*{Test sheet: stacked above marks (draft)}
The use case: a letter followed by two above marks in a chosen order, set as typed. Two paths:
\textbf{(1) precomposed letter + mark}: HarfBuzz composes the letter and the first mark where a precomposed letter exists (a + ◌̈ → ä), so the second mark attaches to ä by mark-to-base; it needs an above anchor at stacking height (regular ä ö ü and italic ā have the designer's; italic and semibold ä ö ü none);
\textbf{(2) mark-to-mark}: with CGJ after the letter, or a letter with no precomposed form (ɛ̃́, ŋ̈̀), the first mark stays a glyph and the second attaches to it; the fonts' mkmk barely exists (regular: grave and breve as first marks; semibold italic: none), so the second mark goes to the letter's anchor and lands on the first.
Where the whole triplet has a precomposed form (u + ◌̈ + ◌̀ → ǜ), normalization takes the designer's glyph; CGJ after the letter avoids it (last section).

\textbf{Drafts} (patched font + a mark-to-mark lookup and a second mark-to-base lookup for the """ + str(len(info[("regular", "U")]["bases"])) + r""" precomposed letters with one above mark): the first mark (or the precomposed letter) gets a stack anchor at its ink top, on its axis; the second mark's anchor sets the gap, ink to ink.
U: one gap per style, """ + str(UNIFORM_K) + r""" × the median of the ten marks' gaps over x-height letters. P: each mark """ + str(PROPORTIONAL_K) + r""" × its own gap over x-height letters (over H for its .cap form).
The designer's precomposed stacks have gaps of about half the same mark's gap over o (regular lowercase 18--69; semibold 16--45).
\par\medskip
\renewcommand\arraystretch{1.2}
{\small\begin{tabular}{l""" + "r" * len(MARKS) + r"""}
gap, font units""" + "".join(rf" & ◌{chr(m)}" for m in MARKS) + r" \\ \hline")
    for st in FILE:
        cmap_names = list(info[(st, "U")]["gaps"])
        g = info[(st, "U")]["gaps"]
        nocap = [n for n in cmap_names if not n.endswith(".cap")]
        L.append(rf"{LABEL[st]}: over o & " + " & ".join(f"{g[n]:.0f}" for n in nocap) + r" \\")
        L.append(r"\quad stacked, U & " + " & ".join(f"{info[(st, 'U')]['targets'][n]:.0f}" for n in nocap) + r" \\")
        L.append(r"\quad stacked, P & " + " & ".join(f"{info[(st, 'P')]['targets'][n]:.0f}" for n in nocap) + r" \\")
    L.append(r"\end{tabular}}")

    order = ("orig", "patch") + VARIANTS

    def rows(st, strings, size=20, sep=r"\ \ "):
        out = [r"\begin{tabular}{>{\footnotesize}l l}"]
        for v in order:
            colour = r"\color{draft}" if v in VARIANTS else ""
            body = sep.join(tex(s) for s in strings)
            out.append(rf"{VLABEL[v]} & {{{macro[(st, v)]}{colour}\fontsize{{{size}}}{{{size * 1.6:.0f}}}\selectfont {body}}} \\")
        out.append(r"\end{tabular}\par\medskip")
        return out

    for st in FILE:
        L.append(r"\clearpage" + rf"\section*{{{LABEL[st]}}}")
        L.append(r"\subsection*{(1) Precomposed letter + second mark, both orders (ä◌̀ and à◌̈ …)}")
        L += rows(st, pre[:20])
        L += rows(st, pre[20:])
        L.append(r"\subsection*{(2) Letters with no precomposed form (mark-to-mark)}")
        L += rows(st, NO_PRECOMPOSED)
        L.append(r"\subsection*{Whole triplet precomposed: typed plainly (the designer's glyph) | with CGJ after the letter (mark-to-mark)}")
        L += rows(st, [s for s in TRIPLETS] + ["|"] + [s[0] + CGJ + s[1:] for s in TRIPLETS], size=18)
        # grid: a + CGJ + first + second
        L.append(r"\clearpage" + rf"\subsection*{{{LABEL[st]}: a + CGJ + first mark (rows) + second mark (columns), mark-to-mark}}")
        L.append(r"\begin{tabular}{p{12.6cm}p{12.6cm}}")
        cells = []
        for v in order:
            colour = r"\color{draft}" if v in VARIANTS else ""
            grid = [rf"{{\footnotesize {VLABEL[v]}}}\par{{\renewcommand\arraystretch{{1}}"]
            grid.append(r"\begin{tabular}{@{}r" + "c" * len(SECOND) + "@{}}")
            grid.append(" & ".join([""] + [rf"\tiny {NAME[m]}" for m in SECOND]) + r" \\")
            for m1 in FIRST:
                grid.append(" & ".join([rf"\tiny {NAME[m1]}"] + [rf"{{{macro[(st, v)]}{colour}\fontsize{{13}}{{20}}\selectfont \rule[-5pt]{{0pt}}{{20pt}}{tex('a' + CGJ + chr(m1) + chr(m2))}}}" for m2 in SECOND]) + r" \\")
            grid.append(r"\end{tabular}}")
            cells.append("\n".join(grid))
        L.append(cells[0] + " & " + cells[1] + r" \\[4pt]")
        L.append(cells[2] + " & " + cells[3] + r" \\")
        L.append(r"\end{tabular}")
    L.append(r"\end{document}")
    open("tex/stack_test_sheet.tex", "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote tex/stack_test_sheet.tex")


if __name__ == "__main__":
    main()
