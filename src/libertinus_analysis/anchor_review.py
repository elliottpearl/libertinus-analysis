# anchor_review.py
"""
Review of the above/below base anchors of the Latin and IPA letters, as the
patched fonts have them. Writes the "Anchor audit" section of the report,
tex/input/anchor_audit.tex.

Each style gets a candidate font: the patch run again with every in-scope
above/below anchor deleted, so that stages 6-8 refill them. Curated anchors
come back unchanged. The candidate font shows what a "delete" override in
data/fontanchors_audit/overrides.py would give.

The placement tests of anchor_audit.py then run on both fonts, and each anchor
falls in one group, by the action it needs:

    replace   fails in the patched font; the candidate moves it and passes.
              Action: "delete" override.
    curate    fails, and the candidate is the same or fails too.
              Action: curated anchor in data/fontanchors_human/{style}.py.
    judge     passes, but a test is suspicious and the candidate differs.
              Action: "delete" override if the candidate is better.

An anchor marked "keep" in the overrides is out of the groups and is listed
as kept, so the list shrinks as decisions are made.
"""

from __future__ import annotations

import contextlib
import io

from data.ipa.ipa_unicode import unicode_groups

from .anchor_audit import ABOVE, BELOW, SIDE_NAMES, STYLE_KEYS, audit_placement, load_style
from .config import TEX_INPUT_DIR
from .font_context import FONTS
from .font_patching import patch_font
from .font_patching_anchors import load_human_anchors
from .font_patching_deleteanchors import load_audit_overrides
from .tex_helpers import latex_font_style

SCOPE = set(unicode_groups["BASE_LATIN"]["items"]) | set(unicode_groups["BASE_IPA"]["items"])

# A candidate within this of the anchor, in x and y, is the same anchor.
SAME_TOL = 10

STYLE_TITLES = {
    "regular": "Regular",
    "italic": "Italic",
    "semibold": "Semibold",
    "semibold_italic": "Semibold italic",
}

GROUPS = ("replace", "curate", "judge")

GROUP_TITLES = {
    "replace": "Replace: fails, and the candidate passes",
    "curate": "Curate: fails, and the candidate does not help",
    "judge": "Judge: passes, but flagged, and the candidate differs",
}

# Marks used to visualize the anchor: the ones the collision test uses
SAMPLE_MARKS = {
    ABOVE: [0x0307, 0x0304, 0x0302],   # dot, macron, circumflex
    BELOW: [0x0323, 0x0331],           # dot below, macron below
}

# Short tags for the test keys, with their legend
TEST_TAGS = {
    "collision": ("col", "a mark overlaps or crowds the glyph"),
    "inside": ("in", "anchor inside the outline"),
    "side": ("sid", "anchor on the wrong side of the glyph"),
    "extent": ("ext", "anchor x outside the glyph"),
    "aspect": ("asp", "beside an ascender or descender"),
    "reference": ("ref", "y far from the reference values"),
    "clearance": ("clr", "floats far from the glyph"),
    "centre": ("ctr", "far from the centre line"),
    "turned": ("trn", "turned letter not following its source"),
    "precomposed": ("pre", "disagrees with precomposed glyphs"),
}

HEADER = r"""% Generated by anchor_review.py. Do not edit: rerunning overwrites this file.
\providecommand{\ReviewPair}[6]{%
  \begin{tabular}[t]{@{}cc@{}}
  \multicolumn{2}{@{}c@{}}{\tiny #1}\\[1pt]
  {\Large #2} & {\Large #4}\\[1pt]
  {\tiny #3} & {\tiny #5}\\
  \multicolumn{2}{@{}c@{}}{\tiny #6}
  \end{tabular}\hspace{4mm}}
\providecommand{\ReviewItem}[4]{%
  \begin{tabular}[t]{@{}c@{}}{\tiny #1}\\[1pt]{\Large #2}\\[1pt]{\tiny #3}\\{\tiny #4}\end{tabular}\hspace{4mm}}
"""

# ----------------------------------------------------------------------
# Candidate fonts
# ----------------------------------------------------------------------

def build_candidate_font(style_key):
    """Patch the style again with every in-scope above/below anchor deleted."""
    cmap = load_style(style_key)["cmap"]
    deletions = {(cmap[cp], cls) for cp in SCOPE if cp in cmap for cls in (ABOVE, BELOW)}
    with contextlib.redirect_stdout(io.StringIO()):
        patch_font(style_key,
                   output_path=FONTS[f"{style_key}_candidate"]["path"],
                   extra_deletions=deletions)

# ----------------------------------------------------------------------
# Classification
# ----------------------------------------------------------------------

def _fails(entry):
    """The findings that mean a mark does not fit: bad ones, and any overlap."""
    return [(level, key, text) for level, key, text in entry["findings"]
            if level == "bad" or (key == "collision" and not text.startswith("crowded"))]


def _same_anchor(now, candidate):
    return (abs(now["xy"][0] - candidate["xy"][0]) <= SAME_TOL
            and abs(now["xy"][1] - candidate["xy"][1]) <= SAME_TOL)


def _group(now, candidate):
    """Which group the anchor belongs to, or None if it needs no action."""
    same = candidate is None or _same_anchor(now, candidate)
    if _fails(now):
        return "curate" if same or _fails(candidate) else "replace"
    if now["findings"] and not same and not _fails(candidate):
        return "judge"
    return None


def _source(style_key, entry, designer, curated):
    """Where the patched anchor came from: curated, designer or scripted."""
    glyph, cls = entry["glyph"], entry["cls"]
    if cls in curated.get(entry["cp"], {}) or cls in curated.get(glyph, {}):
        return "curated"
    original = designer.get(glyph, {}).get(cls)
    if original and original[0] == entry["xy"][0]:
        return "designer"
    return "scripted"


def review_style(style_key):
    """
    Returns {"groups": {group: [row]}, "kept": [row], "missing": [cp]}.
    A row is {"now": entry, "candidate": entry or None, "source": str}.
    """
    build_candidate_font(style_key)
    patched, ctx = audit_placement(style_key, f"{style_key}_patch", SCOPE)
    candidate, _ = audit_placement(style_key, f"{style_key}_candidate", SCOPE)

    designer = load_style(style_key)["base_anchors"]
    human = load_human_anchors(style_key)
    curated = {**human.get("bases", {}), **human.get("bases_by_name", {})}
    overrides = load_audit_overrides(style_key)

    groups = {group: [] for group in GROUPS}
    kept = []
    for key, now in patched.items():
        glyph, cls = key
        other = candidate.get(key)
        row = {"now": now, "candidate": other,
               "source": _source(style_key, now, designer, curated)}
        if overrides.get(glyph, {}).get(cls) == "keep":
            kept.append(row)
            continue
        group = _group(now, other)
        if group:
            groups[group].append(row)

    missing = [(cp, cls) for cp in sorted(SCOPE) if cp in ctx["cmap"] for cls in (ABOVE, BELOW)
               if (ctx["cmap"][cp], cls) not in patched]
    return {"groups": groups, "kept": kept, "missing": missing, "audited": len(patched)}

# ----------------------------------------------------------------------
# LaTeX
# ----------------------------------------------------------------------

def _samples(font_key, cp, cls):
    samples = [f'\\char"{cp:04X}\\cgj\\char"{mark:04X}' for mark in SAMPLE_MARKS[cls]]
    return latex_font_style(font_key, "\\ ".join(samples))


def _tags(entry):
    tags = []
    for _, key, _ in entry["findings"]:
        if TEST_TAGS[key][0] not in tags:
            tags.append(TEST_TAGS[key][0])
    return " ".join(tags) or "---"


def _xy(entry):
    return f"{entry['xy'][0]}, {entry['xy'][1]}".replace("-", "$-$")


def _label(row):
    now = row["now"]
    return f"{now['cp']:04X} \\texttt{{\\detokenize{{{now['glyph']}}}}}"


def _format_pair(style_key, row):
    now, candidate = row["now"], row["candidate"]
    cp, cls = now["cp"], now["cls"]
    return (f"\\ReviewPair{{{_label(row)}}}"
            f"{{{_samples(f'{style_key}_patch', cp, cls)}}}"
            f"{{{_xy(now)} {row['source']}}}"
            f"{{{_samples(f'{style_key}_candidate', cp, cls)}}}"
            f"{{{_xy(candidate)}}}"
            f"{{{_tags(now)}}}")


def _format_item(style_key, row):
    now = row["now"]
    return (f"\\ReviewItem{{{_label(row)}}}"
            f"{{{_samples(f'{style_key}_patch', now['cp'], now['cls'])}}}"
            f"{{{_xy(now)} {row['source']}}}"
            f"{{{_tags(now)}}}")


def _format_cells(title, cells):
    return [f"\\subsubsection*{{{title}}}", "",
            "{\\raggedright\\lineskip=8pt", *cells, "\\par}", ""]


def format_style(style_key, review):
    lines = [f"\\subsection*{{{STYLE_TITLES[style_key]}}}", ""]

    for group in GROUPS:
        for cls in (ABOVE, BELOW):
            rows = sorted((r for r in review["groups"][group] if r["now"]["cls"] == cls),
                          key=lambda r: r["now"]["cp"])
            if not rows:
                continue
            fmt = _format_item if group == "curate" else _format_pair
            title = f"{GROUP_TITLES[group]}, {SIDE_NAMES[cls]} ({len(rows)})"
            lines += _format_cells(title, [fmt(style_key, row) for row in rows])

    if review["kept"]:
        rows = sorted(review["kept"], key=lambda r: (r["now"]["cls"], r["now"]["cp"]))
        lines += _format_cells(f"Kept ({len(rows)})", [_format_item(style_key, row) for row in rows])

    return "\n".join(lines)


def format_summary(reviews):
    rows = [" & ".join(["", "Replace", "Curate", "Judge", "Kept", "No anchor"]) + r" \\", r"\hline"]
    for style in STYLE_KEYS:
        review = reviews[style]
        counts = [len(review["groups"][group]) for group in GROUPS]
        counts += [len(review["kept"]), len(review["missing"])]
        rows.append(" & ".join([STYLE_TITLES[style], *map(str, counts)]) + r" \\")
    return "\n".join([r"\begin{tabular}{lrrrrr}", *rows, r"\end{tabular}", ""])


def format_legend():
    parts = [f"\\textbf{{{tag}}} {text}" for tag, text in TEST_TAGS.values()]
    return "Tags: " + "; ".join(parts) + "."


def format_review(reviews):
    parts = [HEADER, format_summary(reviews), format_legend(), ""]
    parts.extend(format_style(style, reviews[style]) for style in STYLE_KEYS)
    for style in STYLE_KEYS:
        if reviews[style]["missing"]:
            codes = ", ".join(f"{cp:04X} {SIDE_NAMES[cls]}" for cp, cls in reviews[style]["missing"])
            parts.append(f"{STYLE_TITLES[style]}, no anchor: {codes}.\n")
    return "\n".join(parts)


def write_anchor_review():
    """Build the candidate fonts and write tex/input/anchor_audit.tex."""
    reviews = {style: review_style(style) for style in STYLE_KEYS}
    path = TEX_INPUT_DIR / "anchor_audit.tex"
    path.write_text(format_review(reviews), encoding="utf-8")
    for style in STYLE_KEYS:
        counts = ", ".join(f"{len(reviews[style]['groups'][group])} {group}" for group in GROUPS)
        print(f"[{style}] {reviews[style]['audited']} anchors reviewed: {counts}, "
              f"{len(reviews[style]['kept'])} kept -> {path.name}")
